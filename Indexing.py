# 1D array
import numpy as np
arr=np.array([10,20,30,40])
print(arr)
#Indexing
print("the first element is:")
print(arr[0])
print("the second element is:")
print(arr[1])
print("the third element is:")
print(arr[2])
print("the fourth element is:")
print(arr[3])
#2D array
a=np.array([
    [10,20,30,40],
    [20,40,60,80]
])
print(a[1,1])
print(a[0,0])
print(a[1,3])
